def _run_case(
    conditional: bool, penalty_kwargs: dict[str, Any]
) -> tuple[float, list[list[float]]]:
    """Run one penalty case and return its scalar value and per-parameter gradients."""
    with _single_threaded_torch():
        torch.manual_seed(SEED)  # seed critic init
        d_net = _Critic(conditional)
        generator = torch.Generator().manual_seed(SEED)
        x_gen = torch.randn(BATCH_SIZE, X_SIZE, generator=generator)
        x_data = torch.randn(BATCH_SIZE, X_SIZE, generator=generator)
        y_data = (
            torch.randn(BATCH_SIZE, Y_SIZE, generator=generator)
            if conditional
            else None
        )
        torch.manual_seed(SEED)  # seed interpolation coefficients
        penalty = gradient_penalty(
            d_net, x_gen, x_data, y_data, eager=False, **penalty_kwargs
        )
        penalty.backward()
        # The penalty differentiates the critic's output wrt. its inputs, not
        # wrt. its parameters; the output bias drops out of that derivative,
        # so its `.grad` stays `None` and is frozen here as `[]`
        grads = [
            [] if p.grad is None else p.grad.flatten().tolist()
            for p in d_net.parameters()
        ]
        return penalty.item(), grads


@pytest.mark.parametrize("case_name", list(CASES.keys()))
def test_gradient_penalty_regression(case_name: str) -> None:
    """Reproduce the frozen penalty value and critic gradients for one case."""
    conditional, penalty_kwargs = CASES[case_name]

    value, grads = _run_case(conditional, penalty_kwargs)

    torch.testing.assert_close(
        torch.tensor(value),
        PENALTY_SCALE * torch.tensor(EXPECTED_VALUE[case_name]),
        rtol=REGRESSION_RTOL,
        atol=REGRESSION_ATOL,
    )
    for grad, expected_grad in zip(grads, EXPECTED_GRADS[case_name], strict=True):
        torch.testing.assert_close(
            torch.tensor(grad),
            PENALTY_SCALE * torch.tensor(expected_grad),
            rtol=REGRESSION_RTOL,
            atol=REGRESSION_ATOL,
        )



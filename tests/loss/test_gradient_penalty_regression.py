@contextlib.contextmanager
def _single_threaded_torch() -> Iterator[None]:
    """Force single-threaded CPU ops to remove one source of reduction-order noise."""
    prev_num_threads = torch.get_num_threads()
    torch.set_num_threads(1)
    try:
        yield
    finally:
        torch.set_num_threads(prev_num_threads)


class _Critic(torch.nn.Module):
    """Small MLP critic scoring `x`, or `(x, y)` pairs when conditional."""

    def __init__(self, conditional: bool) -> None:
        super().__init__()
        self.conditional = conditional
        input_size = X_SIZE + Y_SIZE if conditional else X_SIZE
        self.net = torch.nn.Sequential(
            torch.nn.Linear(input_size, 16),
            torch.nn.Tanh(),
            torch.nn.Linear(16, 1),
        )

    def forward(self, x: torch.Tensor, y: torch.Tensor | None = None) -> torch.Tensor:
        """Score `x` alone, or `torch.cat([x, y], dim=1)` when conditional."""
        if self.conditional:
            assert y is not None, "conditional critic requires `y`"
            x = torch.cat([x, y], dim=1)
        return self.net(x)


